-- Copa de Clubes 2026
-- Tablas independientes: no modifica ni elimina datos de la Liga Metropolitana.
create table if not exists public.copa_matches (
  id bigint generated by default as identity primary key,
  tie_code text not null check (tie_code in ('QF1','QF2','QF3','SF1','SF2','FINAL')),
  category text not null,
  home_club text not null,
  away_club text not null,
  match_date date,
  home_goals integer check (home_goals is null or home_goals >= 0),
  away_goals integer check (away_goals is null or away_goals >= 0),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tie_code, category)
);
create table if not exists public.copa_scorers (
  id bigint generated by default as identity primary key,
  player_name text not null,
  club_name text not null,
  category text not null,
  goals integer not null check (goals > 0),
  created_at timestamptz not null default now()
);
create table if not exists public.copa_cards (
  id bigint generated by default as identity primary key,
  player_name text not null,
  club_name text not null,
  category text not null,
  card_type text not null check (card_type in ('Amarilla','Roja')),
  match_id bigint references public.copa_matches(id) on delete set null,
  created_at timestamptz not null default now()
);
alter table public.copa_matches enable row level security;
alter table public.copa_scorers enable row level security;
alter table public.copa_cards enable row level security;
drop policy if exists "Copa public read matches" on public.copa_matches;
create policy "Copa public read matches" on public.copa_matches for select using (true);
drop policy if exists "Copa admin manage matches" on public.copa_matches;
create policy "Copa admin manage matches" on public.copa_matches for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Copa public read scorers" on public.copa_scorers;
create policy "Copa public read scorers" on public.copa_scorers for select using (true);
drop policy if exists "Copa admin manage scorers" on public.copa_scorers;
create policy "Copa admin manage scorers" on public.copa_scorers for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Copa public read cards" on public.copa_cards;
create policy "Copa public read cards" on public.copa_cards for select using (true);
drop policy if exists "Copa admin manage cards" on public.copa_cards;
create policy "Copa admin manage cards" on public.copa_cards for all to authenticated using (public.is_admin()) with check (public.is_admin());
